import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const schema=read("prisma/schema.prisma");
const security=read("src/services/securityService.ts");
const server=read("src/server.ts");
const auth=read("src/services/authService.ts");
const users=read("public/users.html");
const client=read("public/user-security.js");
const failures=[];
const must=(ok,msg)=>{if(!ok) failures.push(msg);};
must(schema.includes("deviceKey"),"device grouping key must be persisted");
must(schema.includes("model IpGeolocationCache"),"IP geolocation cache model must exist");
must(schema.includes("model DataAccessEvent"),"sensitive data access audit model must exist");
must(security.includes("resolveIpGeography"),"IP geolocation resolver must exist");
must(security.includes("ipwho.is"),"configured IP geolocation provider must exist");
must(security.includes("NEW_DEVICE") && security.includes("NEW_LOCATION"),"new device/location detection must exist");
must(security.includes("LOGIN_BURST"),"failed login burst detection must exist");
must(security.includes("listSecurityDevices") && security.includes("listDataAccessEvents"),"security operations queries must exist");
must(security.includes("databaseSecuritySnapshot"),"database security health snapshot must exist");
must(server.includes("/api/admin/security/devices"),"device intelligence endpoint must exist");
must(server.includes("/api/admin/security/data-access"),"data access audit endpoint must exist");
must(server.includes("/api/admin/security/database"),"database security endpoint must exist");
must(server.includes("recordDataAccessEvent"),"sensitive API access must be audited");
must(auth.includes("deviceKey"),"sessions must persist device grouping");
must(users.includes("Device intelligence") && users.includes("Database security controls"),"Users page must expose security operations controls");
must(client.includes("renderSecurityDevices") && client.includes("renderSecurityAccess") && client.includes("renderDatabaseSecurity"),"security operations client must render new layers");
const migration=read("prisma/migrations/20260930133000_security_operations_layer/migration.sql");
must(migration.includes("IpGeolocationCache") && migration.includes("DataAccessEvent"),"security operations migration must exist");
if(failures.length){console.error("SECURITY OPERATIONS REGRESSION CHECK FAILED:"); failures.forEach(x=>console.error(" - "+x)); process.exit(1);}
console.log("Security operations regression checks passed.");
