import assert from "node:assert/strict";
import {createBoundedDimensionCache} from "../src/services/boundedDimensionCache.js";
const cache=createBoundedDimensionCache<string[]>(60_000,2);
let calls=0;
const loader=async()=>{calls++;await Promise.resolve();return ["Old Site","New Site"];};
const values=await Promise.all(Array.from({length:20},()=>cache.get("employer-a",loader)));
assert.equal(calls,1);
assert.deepEqual(values[0],["Old Site","New Site"]);
await cache.get("employer-b",loader);
await cache.get("employer-c",loader);
assert.equal(cache.size(),2);
await cache.get("employer-a",loader);
assert.equal(calls,4);
cache.invalidate("employer-a");
await cache.get("employer-a",loader);
assert.equal(calls,5);
let failureCount=0;
await assert.rejects(cache.get("failed",async()=>{failureCount++;throw new Error("unavailable")}),/unavailable/);
await assert.rejects(cache.get("failed",async()=>{failureCount++;throw new Error("unavailable")}),/unavailable/);
assert.equal(failureCount,2);
assert.throws(()=>createBoundedDimensionCache(301_000,2),/limits/);
assert.throws(()=>createBoundedDimensionCache(60_000,1001),/limits/);
console.log("Bounded dimension cache deduplication, eviction and error-retry passed");
