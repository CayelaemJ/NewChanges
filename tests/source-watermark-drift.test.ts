import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {classifySourceWatermark as decide} from "../src/services/sourceWatermarkDrift.js";
const at=new Date("2026-10-19T08:00:00Z");
assert.equal(decide("2026-10-19T08:00:01Z",at),"CHANGED");
assert.equal(decide("2026-10-19T08:00:00Z",at),"UNCHANGED");
assert.equal(decide("2026-10-19T07:59:59Z",at),"REGRESSED");
assert.equal(decide("2026-10-19 08:00:01",at),"CHANGED");
assert.equal(decide(null,at),"MISSING");
assert.equal(decide("",at),"MISSING");
assert.equal(decide(null,null),"UNCHANGED");
assert.equal(decide("2026-10-19T08:00:00Z",null),"CHANGED");
assert.equal(decide("not a timestamp",at),"INVALID");
assert.equal(decide("not a timestamp",null),"INVALID");
assert.equal(decide("2026-10-19T08:00:00Z",new Date(NaN)),"INVALID");
const sync=readFileSync(new URL("../src/services/syncService.ts",import.meta.url),"utf8");
const server=readFileSync(new URL("../src/server.ts",import.meta.url),"utf8");
assert(sync.includes("classifySourceWatermark(watermark.newest,cursor)"));
assert(sync.includes("changed: anomalies.length===0 && reports.length>0"));
assert(sync.includes("anomalies.push({reportKey,kind:decision})"));
assert(server.includes("sourceAnomalies.length > 0"));
assert(server.includes("ordinary incremental sync paused pending review"));
assert(server.indexOf("sourceAnomalies.length > 0")<server.indexOf("if (changes.supported && changes.changed)"));
console.log("Source watermark drift detects regression, deletion and invalid timestamps without unsafe sync");
