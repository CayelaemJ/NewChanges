import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {sourceChangePollSeconds} from "../src/services/sourceChangePollConfig.js";
assert.equal(sourceChangePollSeconds({}),60);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"30"}),30);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"15"}),30,"Fast source checks must not activate by accident");
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"15",ENABLE_SEMANTIC_FAST_SOURCE_WATCH:"true"}),15);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"15",ENABLE_SEMANTIC_FAST_SOURCE_WATCH:"true",STANDBY_MODE:"true"}),30);

assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"60"}),60);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"12"}),30);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"3601"}),3600);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"bogus"}),60);
assert.equal(sourceChangePollSeconds({SOURCE_CHANGE_POLL_SECONDS:"40.5"}),60);
const scheduler=readFileSync(new URL("../src/server.ts",import.meta.url),"utf8");
const source=readFileSync(new URL("../src/services/syncService.ts",import.meta.url),"utf8");
const admin=readFileSync(new URL("../public/admin.html",import.meta.url),"utf8");
assert(scheduler.includes("if (tickRunning) return;"),"do not overlap watcher ticks");
assert(scheduler.includes("if (changes.supported && changes.changed)"),"detect before ingestion");
assert(scheduler.includes("if (changes.supported && !changes.changed && cfg.lastSuccessfulSyncAt)"),"skip unchanged sources");
assert(scheduler.includes("setInterval(tick, CHECK_MS)"),"schedule incremental checks");
assert(source.includes('sourceChangeSchedulerEnabled:'),"Admin must see actual scheduler enablement");
assert(admin.includes('!c.sourceChangeSchedulerEnabled'),"Admin must warn when watcher paused");
assert(admin.includes('60 seconds by default'),"Admin must describe real default");
assert(!admin.includes("normally 5 minutes"),"remove stale admin documentation");
assert(admin.includes("window.setInterval(refreshVisibleIntegSyncStatus, 60000)"),"Admin integration status must update once per minute");
const statusRefresh=admin.slice(admin.indexOf("async function refreshVisibleIntegSyncStatus"),admin.indexOf("async function loadInteg()"));
assert(statusRefresh.includes("document.visibilityState"),"do not poll hidden Admin tabs");
assert(statusRefresh.includes("getBoundingClientRect"),"poll only visible integration panel");
assert(statusRefresh.includes("renderIntegSyncStatus(await reply.json())"),"refresh current sync status without resetting form fields");
assert(!statusRefresh.includes("integrationDraft()"),"status refresh must not modify unsaved Admin settings");
console.log("Near-real-time SQL watcher interval, non-overlap and Admin truthfulness passed");
