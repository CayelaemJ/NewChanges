import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {CANONICAL_REPLACEMENT_FEEDS} from "../src/services/datasetReplacementStaging.js";
import {reviewStoredReplacementManifest} from "../src/services/datasetReplacementStorageReview.js";
const generationId="g1",sourceFingerprint="a".repeat(64),activeSourceFingerprint="b".repeat(64);
const content=Buffer.from('{"rows":[]}'),digest=createHash("sha256").update(content).digest("hex");
const objects=CANONICAL_REPLACEMENT_FEEDS.map(feed=>({feed,generationId,sourceFingerprint,
 objectKey:`staging/${generationId}/${sourceFingerprint}/${feed}/${digest}.json`,
 expectedSha256:digest,expectedBytes:content.byteLength,rowCount:0}));
const input={generationId,sourceFingerprint,activeSourceFingerprint,
 namespace:`staging/${generationId}/${sourceFingerprint}`,objects};
let count=0;
const reader=async (_key:string)=>{count++;return content;};
assert.equal((await reviewStoredReplacementManifest(input,reader)).readyForStagingReview,true);
assert.equal(count,10);
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:objects.slice(1)},reader)).readyForStagingReview,false);
assert.equal(count,0,"no incomplete manifest should fetch data");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:objects.map((o,i)=>i?o:{...o,objectKey:"production/x.json"})},reader)).readyForStagingReview,false);
assert.equal(count,0,"foreign keys must never be fetched");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:[...objects.slice(0,9),objects[0]]},reader)).readyForStagingReview,false);
assert.equal(count,0,"duplicate feed must not trigger storage reads");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:objects.map((o,i)=>i?o:{...o,expectedSha256:"b".repeat(64)})},reader)).readyForStagingReview,false);
assert.equal(count,0,"filename checksum mismatch must not trigger storage reads");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:objects.map((o,i)=>i?o:{...o,feed:"unknown" as typeof o.feed})},reader)).readyForStagingReview,false);
assert.equal(count,0,"unknown feed must not trigger storage reads");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,namespace:"staging/foreign"},reader)).readyForStagingReview,false);
assert.equal(count,0,"wrong namespace must not trigger storage reads");
count=0;
assert.equal((await reviewStoredReplacementManifest({...input,objects:objects.map((o,i)=>i?o:{...o,rowCount:-1})},reader)).readyForStagingReview,false);
assert.equal(count,0,"negative row count must not trigger storage reads");
assert.equal((await reviewStoredReplacementManifest(input,async()=>Buffer.from("invalid"))).readyForStagingReview,false);
assert.equal((await reviewStoredReplacementManifest(input,async()=>{throw new Error("unavailable")})).readyForStagingReview,false);
count=0;
assert.equal((await reviewStoredReplacementManifest(input,reader,content.length*9)).readyForStagingReview,false);
assert.equal(count,0,"over-budget manifest must not read storage");
count=0;
assert.equal((await reviewStoredReplacementManifest(input,reader,0)).readyForStagingReview,false);
assert.equal(count,0,"invalid budget must not read storage");
count=0;
assert.equal((await reviewStoredReplacementManifest(input,reader,Number.MAX_SAFE_INTEGER)).readyForStagingReview,false);
assert.equal(count,0,"unbounded budget must not read storage");
let reads=0;
const corrupt=Buffer.from(content);corrupt[1]^=1;
const badChecksumReader=async()=>{reads++;return reads===2?corrupt:content;};
const checksumResult=await reviewStoredReplacementManifest(input,badChecksumReader);
assert.equal(checksumResult.readyForStagingReview,false);
assert.equal(reads,2,"checksum failure must stop before third storage read");
reads=0;
const brokenReader=async()=>{reads++;if(reads===3)throw new Error("offline");return content;};
assert.equal((await reviewStoredReplacementManifest(input,brokenReader)).readyForStagingReview,false);
assert.equal(reads,3,"storage failure must stop subsequent reads");
console.log("Trusted staged storage readback checks passed");
